#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md: every package the app ships, with its license
// text, plus the runtime pieces that don't come from npm. Run after changing
// dependencies: `node scripts/third-party-notices.mjs`.
import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const paths = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], { cwd: root, encoding: "utf8" })
  .split("\n").map((p) => p.trim()).filter((p) => p && p !== root);

const packages = new Map();
for (const dir of paths) {
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  } catch {
    continue;
  }
  const key = `${pkg.name}@${pkg.version}`;
  if (packages.has(key)) continue;
  const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "see text";
  const text = file ? fs.readFileSync(path.join(dir, file), "utf8").trim() : "";
  packages.set(key, { name: pkg.name, version: pkg.version, license, text, home: pkg.homepage || pkg.repository?.url || pkg.repository || "" });
}

const list = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
// Packages built for one system (the AI engine's binaries, for one) differ between the Mac, Windows and Linux apps.
const lines = [
  "# Third-party notices",
  "",
  "BubbleFacts is © 2026 Christopher Feyrer and released under the MIT License (see `LICENSE`).",
  "It is built on the open source software below. Each keeps its own copyright and license.",
  "",
  "## Not from npm",
  "",
  "- **Electron**, which includes Chromium and Node.js: MIT License. Chromium's own notices ship inside the app as `LICENSES.chromium.html`. https://www.electronjs.org",
  "- **Node.js**, run by the Linux app's fact server: MIT License, with the notices of the libraries it includes. https://github.com/nodejs/node/blob/main/LICENSE",
  "- **llama.cpp**, the AI engine inside node-llama-cpp: MIT License. https://github.com/ggml-org/llama.cpp",
  "- **Llama 3.2 3B Instruct**, the built-in AI model, downloaded on first run and not bundled: Llama 3.2 Community License. Llama 3.2 is licensed under the Llama 3.2 Community License, Copyright © Meta Platforms, Inc. All Rights Reserved. Built with Llama. https://www.llama.com/llama3_2/license/",
  "- **Facts** are rewritten from Wikipedia (text under CC BY-SA 4.0), with data from Wikidata and MusicBrainz (CC0).",
  "- Some rules for reading a song out of a YouTube title follow **Web Scrobbler metadata-filter** (MIT). https://github.com/web-scrobbler/metadata-filter",
  "",
  `## npm packages (${list.length})`,
  "",
  "Generated by `scripts/third-party-notices.mjs`. Packages built for one system, such as the AI engine's binaries, differ between the Mac, Windows and Linux apps; their licenses are the same.",
  "",
];
for (const p of list) {
  lines.push(`### ${p.name} ${p.version}`, "", `License: ${p.license}${p.home ? `. ${String(p.home).replace(/^git\+/, "")}` : ""}`, "");
  if (p.text) lines.push("```", p.text, "```", "");
}
fs.writeFileSync(path.join(root, "THIRD-PARTY-NOTICES.md"), lines.join("\n"));
console.log(`THIRD-PARTY-NOTICES.md: ${list.length} packages`);
